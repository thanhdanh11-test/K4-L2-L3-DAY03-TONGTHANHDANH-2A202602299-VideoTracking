def build(job, corrections, length):
    ann = json.loads((REVIEW / f'before-job-{job}.json').read_text())
    for tid, points in corrections.items():
        track = ann['tracks'][tid-1]
        previous = {s['frame']: s for s in track['shapes']}
        shapes = []
        for frame, box in sorted(points.items()):
            shape = dict(previous.get(frame-1, track['shapes'][0]))
            shape.pop('id', None)
            shape.update(frame=frame-1, points=box, outside=False, occluded=False)
            shapes.append(shape)
        if max(points) < length:
            shape = dict(shapes[-1])
            shape.update(frame=max(points), outside=True)
            shapes.append(shape)
        track.update(frame=min(points)-1, shapes=shapes)
    if job == 4:
        for tid, ranges in {1: [(26, 33),(41, 51)],2: [(34, 47),(51, 60)],3: [(1, 10)],4: [(10, 25)]}.items():
            for s in ann['tracks'][tid-1]['shapes']:
                if not s['outside'] and any(a<=s['frame']+1<=b for a,b in ranges):
                    s['occluded'] = True
    else:
        for tid, ranges in {1:[(1,4),(104,145),(185,190)],3:[(12,20)],
                            4:[(98,151)],5:[(73,129)],6:[(96,143)],
                            7:[(164,175),(178,190)]}.items():
            for s in ann['tracks'][tid-1]['shapes']:
                if not s['outside'] and any(a<=s['frame']+1<=b for a,b in ranges):
                    s['occluded'] = True
    (REVIEW / f'revised-job-{job}.json').write_text(json.dumps(ann, indent=2)+'\n')
    print(f'job {job}: {sum(not s["outside"] for t in ann["tracks"] for s in t["shapes"])} visible boxes')


