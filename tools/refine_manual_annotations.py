def rows(start, text):
    return {start+i: [float(v) for v in row.split(',')]
            for i, row in enumerate(text.strip().split())}


def dense(anchors):
    """Per-frame keyframes between visually measured anchors, reviewed afterwards."""
    result = {}
    keys = sorted(anchors)
    for a, b in zip(keys, keys[1:]):
        for f in range(a, b):
            result[f] = [round(x+(y-x)*(f-a)/(b-a), 1)
                         for x, y in zip(anchors[a], anchors[b])]
    result[keys[-1]] = anchors[keys[-1]]
    return result


